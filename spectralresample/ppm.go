// DrawText renders an upper-case 5x7 label at scale with one-pixel spacing.
func (c Canvas) DrawText(x, y, scale int, text string, color RGB) {
	cursor := x
	for _, r := range text {
		if r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7['?']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row]&(1<<(4-col)) != 0 {
					c.FillRect(cursor+col*scale, y+row*scale, cursor+(col+1)*scale-1, y+(row+1)*scale-1, color)
				}
			}
		}
		cursor += 6 * scale
	}
}

// TextWidth reports the pixel width occupied by a label at the given scale.
func TextWidth(text string, scale int) int {
	return (6*len(text) - 1) * scale
}
