package spectralresample

import (
	"bufio"
	"fmt"
	"os"
)

// RGB is an 8-bit display pixel.
type RGB struct {
	R, G, B uint8
}

// Canvas is an RGB raster rendered entirely in memory and serialised as a
// binary PPM (P6), which needs no third-party image libraries.
type Canvas struct {
	Width  int
	Height int
	Pixels []RGB
}

// NewCanvas allocates a black canvas.
func NewCanvas(width, height int) Canvas {
	return Canvas{Width: width, Height: height, Pixels: make([]RGB, width*height)}
}

// Set writes a pixel, ignoring out-of-range coordinates.
func (c Canvas) Set(x, y int, color RGB) {
	if x < 0 || y < 0 || x >= c.Width || y >= c.Height {
		return
	}
	c.Pixels[y*c.Width+x] = color
}

// FillRect paints a solid rectangle including both edges.
func (c Canvas) FillRect(x0, y0, x1, y1 int, color RGB) {
	for y := y0; y <= y1; y++ {
		for x := x0; x <= x1; x++ {
			c.Set(x, y, color)
		}
	}
}

// WritePPM serialises the canvas to a binary P6 PPM file.
func (c Canvas) WritePPM(path string) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	if _, err := fmt.Fprintf(w, "P6\n%d %d\n255\n", c.Width, c.Height); err != nil {
		return err
	}
	for _, pixel := range c.Pixels {
		if _, err := w.Write([]byte{pixel.R, pixel.G, pixel.B}); err != nil {
			return err
		}
	}
	return w.Flush()
}

func rgbFrom8(v [3]int) RGB {
	return RGB{R: uint8(v[0]), G: uint8(v[1]), B: uint8(v[2])}
}

