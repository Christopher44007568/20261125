// drawCJK renders one Chinese glyph at the given baseline position.
func (im *RGBA) drawCJK(x, y, size int, r rune, col [3]float64, alpha float64) {
	glyph, ok := cjkGlyph[r]
	if !ok {
		return
	}
	scale := float64(size) / 100
	for _, stroke := range glyph {
		for k := 0; k < len(stroke)-1; k++ {
			p0 := stroke[k]
			p1 := stroke[k+1]
			im.drawLine(
				float64(x)+p0[0]*scale, float64(y)+p0[1]*scale,
				float64(x)+p1[0]*scale, float64(y)+p1[1]*scale,
				col, alpha, float64(size)/42+0.8,
			)
		}
	}
}

// drawCJKString renders a run of authored glyphs with tracking.
func (im *RGBA) drawCJKString(x, y, size int, text string, col [3]float64, alpha float64) int {
	cx := x
	for _, r := range text {
		if _, ok := cjkGlyph[r]; ok {
			im.drawCJK(cx, y, size, r, col, alpha)
			cx += size + size/8
		}
	}
	return cx
}

// cjkWidth mirrors drawCJKString advance for layout.
func cjkWidth(text string, size int) int {
	n := 0
	for _, r := range text {
		if _, ok := cjkGlyph[r]; !ok {
			continue
		}
		n++
	}
	return n * (size + size/8)
}
