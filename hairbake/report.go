package main

import (
	"fmt"
	"os"
)

func writeReport(path string, g *Groom, res *BakeResult) error {
	flyTotal := 0
	for _, s := range g.Strands {
		if s.Flyaway {
			flyTotal++
		}
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	pct := func(x float64) string { return fmt.Sprintf("%.1f%%", x*100) }
	fmt.Fprintf(f, "# Hair Card Bake Report\n\n")
	fmt.Fprintf(f, "Generated by the pure-Go-stdlib pipeline in `hairbake/`.\n\n")
	fmt.Fprintf(f, "## Reduction\n\n")
	fmt.Fprintf(f, "- Input strands: %d (each %d segments)\n", len(g.Strands), segments)
	fmt.Fprintf(f, "- Flyaway strands: %d (%s of groom)\n", flyTotal, pct(float64(flyTotal)/float64(len(g.Strands))))
	fmt.Fprintf(f, "- Output hair cards: %d (budget-priority: silhouette > highlight > interior detail)\n", len(res.Cards))
	fmt.Fprintf(f, "- Mean strand-to-card-center distance: %.3f units, max %.3f units\n", res.MeanDist, res.MaxDist)
	fmt.Fprintf(f, "- Silhouette IoU (reference vs cards, front view): %s\n", pct(res.SilhouetteIOU))
	fmt.Fprintf(f, "- Highlight energy retention (specular pixel sum): %s\n", pct(res.SpecRetention))

	fmt.Fprintf(f, "\n## Flyaway audit\n\n")
	fmt.Fprintf(f, "- Lost flyaways (tip outside ribbon width): %d / %d\n", len(res.LostFlyaways), flyTotal)
	fmt.Fprintf(f, "- Retained flyaways: %d\n", len(res.KeptFlyaways))
	fmt.Fprintf(f, "- Lost tips are ringed in red in `side_by_side.png`, `closeup.png` and `montage_views.png`.\n")
	fmt.Fprintf(f, "- The card budget (%d) forces wide silhouette ribbons; sparse outward arcs cannot be\n", cardCount)
	fmt.Fprintf(f, "  represented without dedicated cards, so their tips are the dominant loss.\n")

	fmt.Fprintf(f, "\n## Texture seams\n\n")
	fmt.Fprintf(f, "- Atlas: %dx%d, %dx%d island grid with %dpx empty gutters (see `atlas_annotated.png`).\n",
		atlasSize, atlasSize, atlasCols, atlasRows, atlasPad)
	fmt.Fprintf(f, "- Yellow dashed lines mark island borders; gutters are intentionally unfilled so\n")
	fmt.Fprintf(f, "  filtering at card edges exposes the seam in the card renders.\n")
	fmt.Fprintf(f, "- Card-row views overlay the same dashed borders directly on the head (`montage_views.png`).\n")

	fmt.Fprintf(f, "\n## Outputs\n\n")
	for _, name := range []string{
		"atlas_color.png", "atlas_flow_spec.png", "atlas_annotated.png",
		"side_by_side.png", "closeup.png", "montage_views.png",
		"render_reference_front.png", "render_cards_front.png", "summary.json",
	} {
		fmt.Fprintf(f, "- `%s`\n", name)
	}

	fmt.Fprintf(f, "\n## Reproduce\n\n")
	fmt.Fprintf(f, "```\ngo run ./hairbake [output-dir]\n```\n")
	return nil
}

func writeSummaryJSON(path string, g *Groom, res *BakeResult) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	flyTotal, flyLost := 0, len(res.LostFlyaways)
	for _, s := range g.Strands {
		if s.Flyaway {
			flyTotal++
		}
	}
	fmt.Fprintf(f, "{\n")
	fmt.Fprintf(f, "  \"strands\": %d,\n", len(g.Strands))
	fmt.Fprintf(f, "  \"segmentsPerStrand\": %d,\n", segments)
	fmt.Fprintf(f, "  \"cards\": %d,\n", len(res.Cards))
	fmt.Fprintf(f, "  \"flyawayTotal\": %d,\n", flyTotal)
	fmt.Fprintf(f, "  \"flyawayLost\": %d,\n", flyLost)
	fmt.Fprintf(f, "  \"flyawayRetained\": %d,\n", len(res.KeptFlyaways))
	fmt.Fprintf(f, "  \"silhouetteIOU\": %.4f,\n", res.SilhouetteIOU)
	fmt.Fprintf(f, "  \"highlightRetention\": %.4f,\n", res.SpecRetention)
	fmt.Fprintf(f, "  \"meanCardDistance\": %.4f,\n", res.MeanDist)
	fmt.Fprintf(f, "  \"maxCardDistance\": %.4f,\n", res.MaxDist)
	fmt.Fprintf(f, "  \"lostFlyawayIDs\": %v,\n", res.LostFlyaways)
	fmt.Fprintf(f, "  \"atlas\": {\"size\": %d, \"cols\": %d, \"rows\": %d, \"padding\": %d}\n",
		atlasSize, atlasCols, atlasRows, atlasPad)
	fmt.Fprintf(f, "}\n")
	return nil
}
