// TextWidth returns the rendered width in pixels.
func TextWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return (len([]rune(text))*6 - 1) * scale
}

// DrawText draws uppercase bitmap text with a 5x7 cell and one-cell spacing.
func DrawText(c *Canvas, x, y, scale int, text string, col color.NRGBA) {
	cursor := x
	for _, r := range []rune(text) {
		if r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		glyph, ok := glyphs[r]
		if !ok {
			glyph = glyphs['?']
		}
		for gy, row := range glyph {
			for gx, bit := range row {
				if bit != '1' {
					continue
				}
				c.FillRect(cursor+gx*scale, y+gy*scale, scale, scale, col)
			}
		}
		cursor += 6 * scale
	}
}
