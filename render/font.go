// TextWidth returns the pixel width of s at the given character scale.
func TextWidth(s string, scale int) int {
	return len(s) * (5*scale + scale)
}

// DrawText renders s with top-left at (x, y) using the 5x7 font.
func (c *Canvas) DrawText(x, y, scale int, s string, col color.Color) {
	cx := x
	for _, r := range s {
		g, ok := glyph5x7[r]
		if !ok {
			g = glyph5x7[' ']
		}
		for ci := 0; ci < 5; ci++ {
			mask := g[ci]
			for row := 0; row < 7; row++ {
				if mask&(1<<row) != 0 {
					c.Rect(cx+ci*scale, y+row*scale, scale, scale, col)
				}
			}
		}
		cx += 6 * scale
	}
}
