func drawText(c *Canvas, x, y int, text string, scale int, col RGB, alpha float64, tracking int) int {
	cursor := x
	for _, ch := range text {
		g, ok := glyphs[ch]
		if !ok {
			g = glyphs[' ']
		}
		for row := 0; row < 7; row++ {
			for colIdx := 0; colIdx < 5; colIdx++ {
				if g[row]&(1<<uint(4-colIdx)) == 0 {
					continue
				}
				for oy := 0; oy < scale; oy++ {
					for ox := 0; ox < scale; ox++ {
						px, py := cursor+colIdx*scale+ox, y+row*scale+oy
						if px >= 0 && py >= 0 && px < c.W && py < c.H {
							i := py*c.W + px
							c.Pix[i] = over(c.Pix[i], premul(col, alpha))
						}
					}
				}
			}
		}
		cursor += 5*scale + tracking
	}
	return cursor
}

func drawCaption(c *Canvas, text, sub string) {
	scale := max(2, c.H/300)
	if c.W < 900 {
		scale = 2
	}
	x := max(22, c.W/38)
	y := c.H - 7*scale*2 - max(28, c.H/22)
	drawText(c, x, y, text, scale, C(0.82, 0.74, 0.58), 0.92, scale)
	if sub != "" {
		drawText(c, x, y+9*scale, sub, max(1, scale-1), C(0.43, 0.56, 0.54), 0.84, max(1, scale-1))
	}
	accent := C(0.93, 0.48, 0.17)
	for yy := 0; yy < 7*scale; yy++ {
		for xx := 0; xx < max(2, scale/2); xx++ {
			c.Pix[(y+yy)*c.W+x-max(14, 2*scale)+xx] = premul(accent, 0.92)
		}
	}
}
