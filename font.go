func textWidth(text string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len([]rune(text)) * 6 * scale
}

func drawText(img *image.NRGBA, x, y, scale int, text string, col color.NRGBA) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range text {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7['?']
		}
		for row, line := range glyph {
			for colIndex, bit := range line {
				if bit != '1' {
					continue
				}
				fillRect(img, cx+colIndex*scale, y+row*scale, scale, scale, col)
			}
		}
		cx += 6 * scale
	}
}

func drawTextCentered(img *image.NRGBA, cx, y, scale int, text string, col color.NRGBA) {
	drawText(img, cx-textWidth(text, scale)/2, y, scale, text, col)
}

func fillRect(img *image.NRGBA, x, y, w, h int, col color.NRGBA) {
	b := img.Bounds()
	x0 := maxInt(x, b.Min.X)
	y0 := maxInt(y, b.Min.Y)
	x1 := minInt(x+w, b.Max.X)
	y1 := minInt(y+h, b.Max.Y)
	for yy := y0; yy < y1; yy++ {
		off := img.PixOffset(x0, yy)
		for xx := x0; xx < x1; xx++ {
			i := off + (xx-x0)*4
			img.Pix[i+0] = col.R
			img.Pix[i+1] = col.G
			img.Pix[i+2] = col.B
			img.Pix[i+3] = col.A
		}
	}
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

func minInt(a, b int) int {
	if a < b {
		return a
	}
	return b
}
