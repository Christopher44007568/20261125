// drawText renders s at (x, y) with integer pixel scaling into img.
func drawText(img *Canvas, x, y, scale int, s string, c color.RGBA) {
	cx := x
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs[' ']
		}
		for row := 0; row < 5; row++ {
			for col := 0; col < 3; col++ {
				if g[row][col] != '#' {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						img.Set(cx+col*scale+dx, y+row*scale+dy, c)
					}
				}
			}
		}
		cx += 4 * scale
	}
}

// textWidth returns the pixel width of s at the given scale.
func textWidth(scale int, s string) int {
	if len(s) == 0 {
		return 0
	}
	return len(s)*4*scale - scale
}
