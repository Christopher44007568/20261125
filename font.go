func GlyphFor(r rune) [7]string {
	if g, ok := font5x7[r]; ok {
		return g
	}
	if upper := unicode.ToUpper(r); upper != r {
		if g, ok := font5x7[upper]; ok {
			return g
		}
	}
	return font5x7['?']
}

// TextWidthM returns layout width in meters. Each glyph uses five columns and
// one column of advance spacing; HeightM is the seven-texel em/cap height.
func TextWidthM(text string, heightM float64) float64 {
	if len(text) == 0 {
		return 0
	}
	pixel := heightM / 7.0
	return float64(6*len(text)-1) * pixel
}
