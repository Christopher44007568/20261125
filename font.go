func textWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return len(text)*6*scale - scale
}

func drawText(img *image.RGBA, x, y int, text string, scale int, c Color) {
	if scale < 1 {
		scale = 1
	}
	cursor := x
	for _, ch := range strings.ToUpper(text) {
		glyph, ok := font5x7[ch]
		if !ok {
			glyph = font5x7['?']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row][col] != '1' {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						setPixel(img, cursor+col*scale+dx, y+row*scale+dy, c)
					}
				}
			}
		}
		cursor += 6 * scale
	}
}

func setPixel(img *image.RGBA, x, y int, c Color) {
	if !image.Pt(x, y).In(img.Bounds()) {
		return
	}
	o := y*img.Stride + x*4
	if c.A == 255 {
		img.Pix[o+0] = c.R
		img.Pix[o+1] = c.G
		img.Pix[o+2] = c.B
		img.Pix[o+3] = 255
		return
	}
	a := float64(c.A) / 255
	img.Pix[o+0] = uint8(float64(img.Pix[o+0])*(1-a) + float64(c.R)*a)
	img.Pix[o+1] = uint8(float64(img.Pix[o+1])*(1-a) + float64(c.G)*a)
	img.Pix[o+2] = uint8(float64(img.Pix[o+2])*(1-a) + float64(c.B)*a)
	img.Pix[o+3] = 255
}
