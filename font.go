func drawText(img *image.RGBA, x, y int, text string, scale int, c RGB) {
	r, g, b := c.Bytes()
	cursor := x
	for _, ch := range strings.ToUpper(text) {
		glyph, ok := font5x7[ch]
		if !ok {
			glyph = font5x7[' ']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row][col] != '1' {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						px, py := cursor+col*scale+dx, y+row*scale+dy
						if !image.Pt(px, py).In(img.Bounds()) {
							continue
						}
						o := py*img.Stride + px*4
						img.Pix[o+0] = r
						img.Pix[o+1] = g
						img.Pix[o+2] = b
						img.Pix[o+3] = 255
					}
				}
			}
		}
		cursor += 6 * scale
	}
}

func drawTextShadow(img *image.RGBA, x, y int, text string, scale int, c RGB) {
	drawText(img, x+scale, y+scale, text, scale, RGB{0.01, 0.012, 0.018})
	drawText(img, x, y, text, scale, c)
}

func textWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return (6*len(text) - 1) * scale
}
