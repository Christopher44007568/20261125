func DrawText(c *Canvas, x, y int, text string, scale int, col RGB) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, ch := range text {
		if ch == ' ' {
			cx += 6 * scale
			continue
		}
		g, ok := glyphs[ch]
		if !ok {
			cx += 6 * scale
			continue
		}
		for row, line := range g {
			for colIdx, bit := range line {
				if bit != '#' {
					continue
				}
				for yy := 0; yy < scale; yy++ {
					for xx := 0; xx < scale; xx++ {
						c.Set(cx+colIdx*scale+xx, y+row*scale+yy, col)
					}
				}
			}
		}
		cx += 6 * scale
	}
}
